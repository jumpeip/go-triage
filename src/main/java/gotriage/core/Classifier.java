	private void score() {
		for (FuncInfo f : r.funcs) {
			if (f.category == Category.RUNTIME || f.category == Category.STDLIB
					|| f.category == Category.GENERATED && !f.isActorGenerated()) {
				continue;
			}
			double score = 0;
			for (Map.Entry<String, String> e : f.caps.entrySet()) {
				int w = kb.weight(e.getKey());
				score += w;
				f.riskReasons.add(e.getKey() + " (+" + w + "): " + e.getValue());
			}
			for (Map.Entry<String, String> e : f.transitiveCaps.entrySet()) {
				int w = (int) Math.round(kb.weight(e.getKey()) * 0.35);
				score += w;
				f.riskReasons.add(e.getKey() + " (indirect, +" + w + "): " + e.getValue());
			}
			Set<String> all = f.allCaps();
			for (String[] combo : COMBOS) {
				int groups = combo.length - 2;
				boolean ok = true;
				for (int g = 0; g < groups && ok; g++) {
					boolean any = false;
					for (String cap : combo[g].split(",")) {
						if (all.contains(cap)) {
							any = true;
							break;
						}
					}
					ok = any;
				}
				if (ok) {
					int bonus = Integer.parseInt(combo[groups]);
					score += bonus;
					f.riskReasons.add("Pattern (+" + bonus + "): " + combo[groups + 1]);
				}
			}
			// notable / offensive libraries used directly
			Set<String> notable = new java.util.LinkedHashSet<>();
			for (int c : f.callees) {
				PackageInfo pi = r.packages.get(r.funcs.get(c).packagePath());
				if (pi != null && pi.library != null && pi.library.libClass().equals("offensive")
						&& !f.packagePath().equals(pi.path)) {
					notable.add(pi.library.prefix() + " (" + pi.library.description() + ")");
				}
			}
			for (String n : notable) {
				score += 20;
				f.riskReasons.add("Offensive library (+20): calls into " + n);
			}
			if (f.category == Category.THIRD_PARTY) {
				score *= 0.5; // library behaviour: still visible, but ranked below actor code
			}
			f.risk = (int) Math.min(100, Math.round(score));
		}
	}

	private void aggregate() {
		for (FuncInfo f : r.funcs) {
			PackageInfo pi = r.packages.get(f.packagePath());
			if (pi == null) {
				continue;
			}
			if (f.isActor()) {
				pi.actorFuncs++;
			}
			pi.maxRisk = Math.max(pi.maxRisk, f.risk);
			if (f.category != Category.RUNTIME) {
				pi.caps.addAll(f.caps.keySet());
			}
		}
	}

	/** Build-environment artefacts: actor source directories and user names leaked by paths. */
	private void buildEnvironment() {
		for (PackageInfo pi : r.packages.values()) {
			for (String f : pi.files) {
				String nf = norm(f);
				FileKind k = fileKind(nf);
				if (k == FileKind.LOCAL_ABS && pi.category.isActorLike() && r.buildPaths.size() < 64) {
					r.buildPaths.add(dirOf(nf));
				}
				if (k == FileKind.LOCAL_ABS || k == FileKind.MODCACHE || k == FileKind.VENDOR) {
					String where = k == FileKind.LOCAL_ABS && pi.category.isActorLike() ? "source tree"
							: k == FileKind.LOCAL_ABS ? "local path" : "GOPATH/module cache";
					addUser(nf, where);
				}
			}
		}
		if (r.goroot != null && !r.goroot.isEmpty()) {
			addUser(r.goroot + "/", "GOROOT");
		}
		boolean ci = false;
		for (String u : r.buildUsers) {
			String name = u.contains(" ") ? u.substring(0, u.indexOf(' ')) : u;
			if (name.equals("runneradmin") || name.equals("runner") || name.equals("vsts") || name.startsWith("buildkite")
					|| name.equals("VssAdministrator")) {
				ci = true;
			}
		}
		for (String p : r.buildPaths) {
			if (p.startsWith("D:/a/") || p.startsWith("/home/runner/work/") || p.startsWith("/Users/runner/work/")
					|| p.startsWith("C:/hostedtoolcache") || p.contains("/builds/") && p.contains("gitlab")) {
				ci = true;
			}
		}
		if (r.goroot != null && (r.goroot.contains("hostedtoolcache") || r.goroot.startsWith("/opt/hostedtoolcache"))) {
			ci = true;
		}
		if (ci) {
			r.notes.add("Built on a CI runner (GitHub Actions / Azure Pipelines style paths): build-path "
					+ "and user-name artefacts identify the CI image, not a person");
		}
	}

	private void addUser(String path, String where) {
		if (r.buildUsers.size() >= 32) {
			return;
		}
		Matcher mw = USER_WIN.matcher(path);
		if (mw.find()) {
			r.buildUsers.add(mw.group(1) + " (" + where + ")");
			return;
		}
		Matcher mu = USER_UNIX.matcher(path);
		if (mu.find()) {
			r.buildUsers.add(mu.group(1) + " (" + where + ")");
			return;
		}
		if (path.startsWith("/root/")) {
			r.buildUsers.add("root (" + where + ")");
		}
	}

	static String shorten(String n) {
		return n.length() > 90 ? n.substring(0, 87) + "..." : n;
	}

	static String clip(String s, int n) {
		String t = s.replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t");
		return t.length() > n ? t.substring(0, n - 3) + "..." : t;
	}
